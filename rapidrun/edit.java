    void saveEditedContentToFile(String editedContent) {
    try {
        String filePath = "D:/horse_info.txt";
        FileWriter writer = new FileWriter(filePath);
        writer.write(editedContent);
        writer.close();
    } catch (IOException ex) {
        JOptionPane.showMessageDialog(this, "Error saving edits.");
        ex.printStackTrace();
    }
    }
