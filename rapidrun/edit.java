    void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        try {
        // Specify the path to the horse_info.txt file on local disk D
        String filePath = "D:/horse_info.txt";
        
        // Read the contents of the file
        BufferedReader reader = new BufferedReader(new FileReader(filePath));
        StringBuilder sb = new StringBuilder();
        String line;
        while ((line = reader.readLine()) != null) {
            sb.append(line).append("\n");
        }
        reader.close();
        
        // Display the contents in the jTextArea1
        jTextArea1.setText(sb.toString());
        } catch (IOException ex) {
        JOptionPane.showMessageDialog(this, "Error reading horse information.");
        ex.printStackTrace();
        }
    }//GEN-LAST:event_jButton1ActionPerformed

