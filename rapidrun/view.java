    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        try {
    String filePath = "D:/horse_info.txt";
    BufferedReader reader = new BufferedReader(new FileReader(filePath));
    List<String[]> rows = new ArrayList<>();
    String line;
    String[] currentRow = new String[8]; // Update the array size to 8
    int index = 0;
    while ((line = reader.readLine()) != null) {
        String[] parts = line.split(": ");
        if (parts.length == 2) {
            currentRow[index++] = parts[1];
            if (index == 8) {
                rows.add(currentRow);
                currentRow = new String[8]; // Reset the array for the next row
                index = 0;
            }
        }
    }
    reader.close();

    DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
    model.setRowCount(0);
    for (String[] row : rows) {
        model.addRow(row);
    }
    } catch (IOException ex) {
    JOptionPane.showMessageDialog(this, "Error reading horse information.");
    ex.printStackTrace();
    }
    }//GEN-LAST:event_jButton1ActionPerformed

