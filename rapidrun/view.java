    private void displayImage(String imagePath) {
    try {
        ImageIcon icon = new ImageIcon(imagePath);
        Image image = icon.getImage();
        Image scaledImage = image.getScaledInstance(jLabel2.getWidth(), jLabel2.getHeight(), Image.SCALE_SMOOTH);
        jLabel2.setIcon(new ImageIcon(scaledImage));
    } catch (Exception ex) {
        JOptionPane.showMessageDialog(this, "Error loading image.");
        ex.printStackTrace();
    }
    }
    private String getImagePathFromTextFile(String horseName) {
    String filePath = "D:/horse_info.txt";
    try (BufferedReader reader = new BufferedReader(new FileReader(filePath))) {
        String line;
        while ((line = reader.readLine()) != null) {
            if (line.startsWith("Horse Name: " + horseName)) {
                String[] parts = line.split(": ");
                if (parts.length == 2) {
                    return parts[1];
                }
            }
        }
    } catch (IOException ex) {
        JOptionPane.showMessageDialog(this, "Error reading horse information.");
        ex.printStackTrace();
    }
    return null;
    }
  

    
    
    

